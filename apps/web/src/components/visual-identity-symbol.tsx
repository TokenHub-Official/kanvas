function iconFor(value: string): React.JSX.Element {
  return (
    visualIdentityIconOptions.find((option) => option.value === value)
      ?.icon ?? <RobotIcon aria-hidden="true" weight="duotone" size="1em" />
  );
}

export function VisualIdentityMark({
  value,
  alt,
  className = "size-12 rounded-[14px] text-xl",
}: {
  readonly value: VisualIdentitySymbol;
  readonly alt: string;
  readonly className?: string;
}): React.JSX.Element {
  return (
    <span
      role="img"
      aria-label={alt}
      className={`relative grid shrink-0 place-items-center overflow-hidden border border-black/5 text-primary ${className}`}
      style={{
        backgroundColor: value.backgroundColor,
        ...(value.kind === "icon" && value.foregroundColor
          ? { color: value.foregroundColor }
          : {}),
      }}
    >
      {value.kind === "emoji" ? (
        <span
          aria-hidden="true"
          className="grid size-[1em] place-items-center leading-none"
        >
          <FluentEmoji emoji={value.value} />
        </span>
      ) : (
        iconFor(value.value)
      )}
    </span>
  );
}
