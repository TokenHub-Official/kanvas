CREATE TABLE `provider_result_recovery` (
  `id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL PRIMARY KEY,
  `instance_id` varchar(120) NOT NULL,
  `workspace_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `capability_run_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `attempt_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `observation_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `result_index` int unsigned NOT NULL,
  `request_key` varchar(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `actor_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `authority_snapshot` json NOT NULL,
  `state` varchar(16) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `error_code` varchar(160) NULL,
  `policy_version` int unsigned NULL,
  `lease_token` char(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  `lease_until` datetime(3) NULL,
  `upload_session_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `stored_object_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `artifact_id` char(26) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `created_at` datetime(3) NOT NULL,
  `updated_at` datetime(3) NOT NULL,
  UNIQUE KEY `uq_result_recovery_request` (`workspace_id`, `capability_run_id`, `request_key`, `result_index`),
  KEY `ix_result_recovery_work` (`state`, `lease_until`, `created_at`),
  CONSTRAINT `fk_result_recovery_instance` FOREIGN KEY (`instance_id`) REFERENCES `instance_runtime_state` (`instance_id`),
  CONSTRAINT `fk_result_recovery_run` FOREIGN KEY (`capability_run_id`) REFERENCES `capability_run` (`id`),
  CONSTRAINT `fk_result_recovery_observation` FOREIGN KEY (`observation_id`) REFERENCES `provider_invocation_observation` (`id`),
  CONSTRAINT `chk_result_recovery_state` CHECK (`state` IN ('queued','running','succeeded','failed'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
