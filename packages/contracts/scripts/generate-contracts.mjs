import { mkdir, readdir, unlink, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

import { routeRegistry } from "../dist/api/index.js";
import {
  WorkflowJsonValueSchema,
  WorkflowValueTemplateSchema,
} from "../dist/workflow/index.js";
import { EditorNodeV1Schema } from "../dist/editor/index.js";

const generatedRoot = resolve(import.meta.dirname, "../generated");
const schemaRoot = resolve(generatedRoot, "schemas");

const openApiReferences = new Map([
  [EditorNodeV1Schema.$id, "#/components/schemas/EditorNodeV1"],
  [WorkflowJsonValueSchema.$id, "#/components/schemas/WorkflowJsonValue"],
  [
    WorkflowValueTemplateSchema.$id,
    "#/components/schemas/WorkflowValueTemplate",
  ],
]);

function projectOpenApiSchema(value) {
  if (Array.isArray(value)) {
    return value.map((item) => projectOpenApiSchema(item));
  }
  if (!value || typeof value !== "object") {
    return value;
  }
  const projected = {};
  for (const [key, item] of Object.entries(value)) {
    if (key === "$id" || key === "$defs") {
      continue;
    }
    if (
      key === "$ref" &&
      typeof item === "string" &&
      openApiReferences.has(item)
    ) {
      projected[key] = openApiReferences.get(item);
      continue;
    }
    projected[key] = projectOpenApiSchema(item);
  }
  return projected;
}

await mkdir(schemaRoot, { recursive: true });

const schemas = new Map();
for (const route of routeRegistry) {
  if (route.request?.body?.$id) {
    schemas.set(route.request.body.$id, route.request.body);
  }
  if (route.request?.query?.$id) {
    schemas.set(route.request.query.$id, route.request.query);
  }
  for (const schema of Object.values(route.responses)) {
    if (schema.$id) {
      schemas.set(schema.$id, schema);
    }
  }
}

const expectedSchemaFiles = new Set(
  [...schemas.keys()].map((schemaId) => `${schemaId}.json`),
);
for (const entry of await readdir(schemaRoot, {
  withFileTypes: true,
})) {
  if (
    entry.isFile() &&
    entry.name.endsWith(".json") &&
    !expectedSchemaFiles.has(entry.name)
  ) {
    await unlink(resolve(schemaRoot, entry.name));
  }
}

for (const [schemaId, schema] of [...schemas].sort(([left], [right]) =>
  left.localeCompare(right),
)) {
  await writeFile(
    resolve(schemaRoot, `${schemaId}.json`),
    `${JSON.stringify(
      {
        $comment:
          "Generated by Kanvas. Do not edit directly. Run pnpm generate:contracts.",
        ...schema,
      },
      null,
      2,
    )}\n`,
    "utf8",
  );
}

const paths = {};
const securityRequirements = {
  public: undefined,
  browserSession: [{ browserSession: [] }],
  browserAttemptGrant: [{ browserAttemptGrant: [] }],
  sessionOrServiceToken: [{ browserSession: [] }, { serviceBearer: [] }],
};
for (const route of routeRegistry) {
  const method = route.method.toLowerCase();
  const operation = {
    operationId: route.operationId,
    summary: route.summary,
    security: route.security.flatMap(
      (security) => securityRequirements[security] ?? [],
    ),
    responses: Object.fromEntries(
      Object.entries(route.responses).map(([status, schema]) => [
        status,
        {
          description: status.startsWith("2") ? "Success" : "Error",
          content: {
            [route.responseContentTypes?.[status] ?? "application/json"]: {
              schema: projectOpenApiSchema(schema),
            },
          },
        },
      ]),
    ),
  };

  if (route.request?.body) {
    operation.requestBody = {
      required: true,
      content: {
        "application/json": {
          schema: projectOpenApiSchema(route.request.body),
        },
      },
    };
  }
  if (route.request?.rawBody) {
    operation.requestBody = {
      required: true,
      content: Object.fromEntries(
        route.request.rawBody.contentTypes.map((contentType) => [
          contentType,
          {
            schema: {
              type: "string",
              format: "binary",
              maxLength: route.request.rawBody.maximumBytes,
            },
          },
        ]),
      ),
    };
  }
  if (route.request?.headers?.properties) {
    operation.parameters = Object.entries(route.request.headers.properties).map(
      ([name, schema]) => ({
        name,
        in: "header",
        required: route.request.headers.required?.includes(name) ?? false,
        schema: projectOpenApiSchema(schema),
      }),
    );
  }
  if (route.request?.path?.properties) {
    operation.parameters = [
      ...(operation.parameters ?? []),
      ...Object.entries(route.request.path.properties).map(
        ([name, schema]) => ({
          name,
          in: "path",
          required: true,
          schema: projectOpenApiSchema(schema),
        }),
      ),
    ];
  }
  if (route.request?.query?.properties) {
    operation.parameters = [
      ...(operation.parameters ?? []),
      ...Object.entries(route.request.query.properties).map(
        ([name, schema]) => ({
          name,
          in: "query",
          required: route.request.query.required?.includes(name) ?? false,
          schema: projectOpenApiSchema(schema),
        }),
      ),
    ];
  }

  paths[route.path] ??= {};
  paths[route.path][method] = operation;
}

const openapi = {
  openapi: "3.1.0",
  "x-kanvas-generated": "Do not edit directly. Run pnpm generate:contracts.",
  info: {
    title: "Kanvas API",
    version: "0.0.0",
  },
  components: {
    securitySchemes: {
      browserSession: {
        type: "apiKey",
        in: "cookie",
        name: "__Host-kanvas.session_token",
        description:
          "Production Better Auth database session cookie. Development uses kanvas.session_token.",
      },
      serviceBearer: {
        type: "http",
        scheme: "bearer",
        bearerFormat: "opaque",
        description:
          "Kanvas Service API token. Raw token material is shown only once.",
      },
      browserAttemptGrant: {
        type: "apiKey",
        in: "header",
        name: "x-kanvas-attempt-grant",
        description:
          "Short-lived grant for exactly one browser assignment. Redact this header from logs and traces.",
      },
    },
    schemas: {
      EditorNodeV1: projectOpenApiSchema(EditorNodeV1Schema),
      WorkflowJsonValue: projectOpenApiSchema(WorkflowJsonValueSchema),
      WorkflowValueTemplate: projectOpenApiSchema(WorkflowValueTemplateSchema),
    },
  },
  paths,
};

await writeFile(
  resolve(generatedRoot, "openapi.json"),
  `${JSON.stringify(openapi, null, 2)}\n`,
  "utf8",
);
